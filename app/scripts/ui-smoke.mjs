/** Browser regression checks. Run against a local simulator, never against the public demo. */
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base = process.env.UI_BASE_URL || 'http://127.0.0.1:4000';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let checks = 0;
const check = (condition, name) => { assert.ok(condition, name); checks++; console.log(`PASS ${name}`); };
try {
  await page.goto(base);
  await page.waitForSelector('.card-grid--catalogue .card');
  check(await page.locator('#view-shop').isHidden(), 'assistant starts closed');
  check(await page.locator('.card-grid--catalogue .card').count() > 0, 'guest catalogue loads');
  await page.click('#assistant-launcher');
  await page.fill('#chat-input', 'laptop under $900 with 16GB RAM');
  await page.click('#chat-send');
  await page.waitForFunction(() => !document.querySelector('#chat-send').disabled);
  check(await page.locator('#chat-log .card').count() > 0, 'assistant returns product cards');
  const messages = await page.locator('#chat-log .msg').count();
  await page.click('#assistant-close');
  await page.click('a[data-nav="orders"]');
  await page.click('#assistant-launcher');
  check(await page.locator('#chat-log .msg').count() === messages, 'navigation preserves chat');
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('#assistant-mode').textContent.includes('Connecting'));
  await page.click('#assistant-launcher');
  check(await page.locator('#chat-log .msg').count() >= 2, 'reload restores session conversation');
  await page.click('#assistant-close');
  await page.click('a[data-nav="catalogue"]');
  await page.locator('.card-grid--catalogue .card').first().getByRole('button', { name: '✦ Ask AI', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('#chat-send').disabled);
  check(await page.locator('#view-shop').isVisible(), 'product Ask AI opens assistant');
  await page.keyboard.press('Escape');
  check(await page.locator('#view-shop').isHidden(), 'Escape closes assistant');
  await page.locator('.card-grid--catalogue .card').first().getByRole('button', { name: 'Add to cart', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('#cart-count').textContent) > 0);
  await page.click('#cart-button');
  await page.waitForSelector('#cart-foot .btn--primary');
  if (await page.locator('#cart-guest-email').count()) await page.fill('#cart-guest-email', `browser-${Date.now()}@example.com`);
  await page.click('#cart-foot .btn--primary');
  await page.waitForURL('**/checkout/**');
  await page.getByRole('button', { name: 'Approve & Pay (simulated PayPal)', exact: true }).waitFor();
  check(await page.locator('#auth-button').innerText() === 'Sign in', 'guest reaches checkout without login');
  await page.getByRole('button', { name: 'Approve & Pay (simulated PayPal)', exact: true }).click();
  await page.waitForFunction(() => document.body.innerText.includes('Payment confirmed') || document.body.innerText.includes('Payment verified') || document.body.innerText.includes('Paid'));
  await page.click('a[data-nav="orders"]');
  await page.waitForSelector('#orders-body tbody tr');
  check(await page.locator('#orders-body').innerText().then(t => t.includes('Orders from this guest session')), 'guest sees own order history');
  await page.click('#auth-button');
  check(await page.inputValue('#auth-email') === '', 'login does not prefill shared demo credentials');
  await page.fill('#auth-email', 'customer@demo.dev');
  await page.fill('#auth-password', 'Customer@12345');
  await page.press('#auth-password', 'Enter');
  await page.waitForSelector('#modal-overlay', { state: 'detached' });
  check(await page.locator('#auth-button').innerText() === 'customer', 'email/password login works');
  await page.click('#auth-button');
  check(await page.getByText('Your account', { exact: true }).isVisible(), 'account button does not silently sign out');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.waitForSelector('#modal-overlay', { state: 'detached' });
  await page.goto(base);
  await page.waitForSelector('.card-grid--catalogue .card');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.click('#assistant-launcher');
  const box = await page.locator('#view-shop').boundingBox();
  check(box.width === 390 && box.height === 844, 'mobile assistant fills viewport');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile page has no horizontal overflow');
  await page.click('#assistant-close');
  await page.click('#theme-toggle');
  check(await page.locator('html').getAttribute('data-theme') === 'dark', 'dark theme works');
  check(errors.length === 0, `no uncaught browser errors: ${errors.join(', ')}`);
  console.log(`${checks} browser checks passed.`);
} finally { await browser.close(); }
